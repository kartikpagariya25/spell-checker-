#!/usr/bin/env node
/*
 * Builds src/dictionary-data.js from a word-frequency list.
 *
 * Input format: one "word<space>count" per line, most frequent first
 * (e.g. SymSpell's en-80k.txt). Usage:
 *
 *   node scripts/build-dictionary.js path/to/en-80k.txt [maxWords]
 *
 * Only plain lowercase words are kept. The output keeps frequency order, so
 * a word's index doubles as its rank (lower index = more common).
 */
'use strict';
const fs = require('fs');
const path = require('path');

const input = process.argv[2];
const maxWords = Number(process.argv[3]) || 45000;

if (!input) {
  console.error('usage: node scripts/build-dictionary.js <frequency-file> [maxWords]');
  process.exit(1);
}

// Entries that appear in raw web-derived frequency lists but are not words
// we want to treat as correct spellings.
const BLOCKLIST = new Set(
  fs
    .readFileSync(path.join(__dirname, 'blocklist.txt'), 'utf8')
    .split(/\r?\n/)
    .map((w) => w.trim())
    .filter((w) => w && !w.startsWith('#'))
);

// Words of 1-3 letters must be on the curated list (see short-words.txt).
const SHORT_WORDS = new Set(
  fs
    .readFileSync(path.join(__dirname, 'short-words.txt'), 'utf8')
    .split(/\r?\n/)
    .filter((l) => l.trim() && !l.startsWith('#'))
    .join(' ')
    .split(/\s+/)
);
const lines = fs.readFileSync(input, 'utf8').split(/\r?\n/);
const words = [];
const seen = new Set();

for (const line of lines) {
  const word = line.split(/\s+/)[0];
  if (!word || !/^[a-z]+$/.test(word)) continue;
  if (word.length <= 3 && !SHORT_WORDS.has(word)) continue;
  if (BLOCKLIST.has(word) || seen.has(word)) continue;
  seen.add(word);
  words.push(word);
  if (words.length >= maxWords) break;
}

const out =
  '// Generated by scripts/build-dictionary.js - do not edit by hand.\n' +
  '(function (root) {\n' +
  "  root.SpellFixWords = '" + words.join(',') + "'.split(',');\n" +
  "})(typeof globalThis !== 'undefined' ? globalThis : this);\n" +
  "if (typeof module !== 'undefined') module.exports = globalThis.SpellFixWords;\n";

fs.mkdirSync(path.join(__dirname, '..', 'src'), { recursive: true });
fs.writeFileSync(path.join(__dirname, '..', 'src', 'dictionary-data.js'), out);
console.log('wrote ' + words.length + ' words');
